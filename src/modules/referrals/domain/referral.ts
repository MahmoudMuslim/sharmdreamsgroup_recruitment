/* Who may see or decide                                                       */
/* -------------------------------------------------------------------------- */

/**
 * Own rows for every staff member; every row for a recruiter or the owner.
 *
 * The RLS policy is the wall behind this function. A hiring manager's board is
 * their own book, including its leaderboard — the person who referred someone is
 * allowed to know how that referral is doing, not to read the whole company's
 * referral history.
 */
export function seesAllReferrals(role: string): boolean {
  return role === "SUPER_ADMIN" || role === "RECRUITER";
}

/** Reassigning a claim is the recruiter's escape from first-claim-wins. */
export function canReassignReferral(role: string): boolean {
  return seesAllReferrals(role);
}

/** The bonus record is a staff decision about money, so it follows the same door. */
export function canDecideBonus(role: string): boolean {
  return seesAllReferrals(role);
}
