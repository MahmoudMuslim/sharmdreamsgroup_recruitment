/**
 * The rules an employee referral has to satisfy, with no database behind them.
 *
 * A referral is a claim by one member of staff on one person for one role. The
 * database owns the two facts this module cannot: the claim is unique per
 * (lower(email), job) so a second claimer loses, and the application's stage is
 * read at display time rather than copied here. Everything a screen or a server
 * action can decide before it writes lives in this file, so the browser's
 * refusal and the action's refusal are the same sentence.
 *
 * Pure by design — no `server-only`, no REST client — because the hand-entry
 * form and the action that receives it both call it.
 */

import type { ApplicationStage } from "@/types";

/** The file that has to be applied before any of this can store a row. */
export const REFERRAL_MIGRATION = "db/migrations/040_referrals.sql";

/**
 * What a screen says when the table is not on the database it is reading.
 *
 * This is a fact about the database, not about the recruiter's board: an empty
 * list is not the same answer as a missing table, and the page must not pretend
 * it has looked at claims it could not read.
 */
export const REFERRAL_SCHEMA_NOTE =
  "The referrals table has not been created on this database yet — " +
  `${REFERRAL_MIGRATION} is authored but not applied. Nothing can be claimed or ` +
  "counted until it is.";

/** The refusal a write returns while the table is missing. */
export const REFERRAL_WRITE_REFUSAL =
  "Referrals cannot be saved until " +
  `${REFERRAL_MIGRATION} is applied to this database.`;

/** How far the board reads before it says it stopped. */
export const REFERRAL_READ_LIMIT = 500;

/** The referral note's own bound, stated in the migration as well. */
export const REFERRAL_NOTE_MAX = 600;

/** The bonus decision's note, held to the same bound as a scorecard's feedback. */
export const REFERRAL_BONUS_NOTE_MAX = 400;

/**
 * A code is ten hexadecimal characters, generated by the database.
 *
 * The length is fixed rather than a range so a mistyped or truncated link is
 * refused instead of crediting a shorter code that happens to exist. Case is
 * folded on the way in: the code in the link is upper-case, and a person who
 * retypes it lower-case still claims their referral.
 */
export const REFERRAL_CODE_PATTERN = /^[0-9A-F]{10}$/;

/** One profile's durable code as it arrives from a URL, or null. */
export function readReferralCode(value: unknown): string | null {
  if (typeof value !== "string") return null;
  const code = value.trim().toUpperCase();
  return REFERRAL_CODE_PATTERN.test(code) ? code : null;
}

/** The role page's public address, carrying the claimant's code. */
export function referralLink(origin: string, jobId: string, code: string): string {
  const base = origin.replace(/\/+$/, "");
  return `${base}/careers/${jobId.trim()}?ref=${encodeURIComponent(code)}`;
}

/**
 * The application step's address for somebody who arrived through a role link.
 *
 * The code has to survive the Apply button: the shared link lands on the ad, and
 * the applicant's referral is only recorded on the submission. Empty origin gives
 * a relative link, which is what a server-rendered page wants.
 */
export function referralApplyLink(origin: string, jobId: string, code: string): string {
  const base = origin.replace(/\/+$/, "");
  return `${base}/careers/apply/${jobId.trim()}?ref=${encodeURIComponent(code)}`;
}

/* -------------------------------------------------------------------------- */
/* Hand entry                                                                  */
/* -------------------------------------------------------------------------- */

const EMAIL_PATTERN = /^[^\s@]+@[^\s@]+\.[^\s@]{2,}$/;
const UUID_PATTERN = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

export type HandEntryPlan =
  | {
      ok: true;
      /** Lower-cased, because the claim's unique key is case-insensitive. */
      email: string;
      fullName: string | null;
      jobId: string;
      note: string | null;
    }
  | { ok: false; error: string };

/**
 * Read a staff member's hand entry as the claim it asks to make, or say why not.
 *
 * The email is the key, so it is folded exactly the way the claim's index folds
 * it. A name is optional — the board identifies a person by their address when
 * that is all the referrer knows — and a blank note is no note, not an empty
 * string the trail would print.
 */
export function planHandEntry(input: {
  email: unknown;
  fullName?: unknown;
  jobId: unknown;
  note?: unknown;
}): HandEntryPlan {
  const email = typeof input.email === "string" ? input.email.trim().toLowerCase() : "";
  if (!email) return { ok: false, error: "Enter the candidate's email address." };
  if (!EMAIL_PATTERN.test(email)) {
    return { ok: false, error: "That email address is not valid." };
  }

  const jobId = typeof input.jobId === "string" ? input.jobId.trim() : "";
  if (!jobId) return { ok: false, error: "Choose the role the candidate was referred to." };
  if (!UUID_PATTERN.test(jobId)) {
    return { ok: false, error: "That role is not one this portal can file against." };
  }

  const typedName = typeof input.fullName === "string" ? input.fullName.trim() : "";
  if (typedName.length > 160) {
    return { ok: false, error: "Keep the name under 160 characters." };
  }

  const typedNote = typeof input.note === "string" ? input.note.trim() : "";
  if (typedNote.length > REFERRAL_NOTE_MAX) {
    return {
      ok: false,
      error: `Keep the note under ${REFERRAL_NOTE_MAX} characters.`,
    };
  }

  return {
    ok: true,
    email,
    fullName: typedName || null,
    jobId,
    note: typedNote || null,
  };
}

/* -------------------------------------------------------------------------- */
/* State, read from the application rather than kept                           */
/* -------------------------------------------------------------------------- */

export type ReferralStage =
  | "invited"
  | "screening"
  | "assessment"
  | "interview"
  | "offer"
  | "hired"
  | "closed";

export interface ReferralProgress {
  key: ReferralStage;
  label: string;
}

/**
 * How far the referred person has got, from the stage the application holds now.
 *
 * Nothing is stored on the referral for this. A stage move changes what every
 * screen reads the next time it loads, which is also why the live channel
 * watches `applications` for the pipeline pages and `referrals` for this one.
 * An absent application is an invitation that has not been taken up; a stage
 * this version does not know is described as the pipeline rather than guessed
 * into hired or closed.
 */
export function referralProgress(stage: string | null | undefined): ReferralProgress {
  if (!stage) return { key: "invited", label: "Not applied yet" };
  switch (stage) {
    case "NEW":
    case "AI_SCREENING":
      return { key: "screening", label: "In screening" };
    case "ASSESSMENT":
      return { key: "assessment", label: "Assessment" };
    case "INTERVIEW":
      return { key: "interview", label: "Interview" };
    case "OFFER":
      return { key: "offer", label: "Offer" };
    case "HIRED":
      return { key: "hired", label: "Hired" };
    case "REJECTED":
      return { key: "closed", label: "Closed" };
    default:
      return { key: "screening", label: "In the pipeline" };
  }
}

export type BonusState = "NONE" | "PENDING" | "PAID" | "DECLINED";

export const BONUS_STATES: readonly BonusState[] = ["NONE", "PENDING", "PAID", "DECLINED"];

export const BONUS_LABELS: Record<BonusState, string> = {
  NONE: "No decision",
  PENDING: "Pending",
  PAID: "Paid",
  DECLINED: "Declined",
};

export function isBonusState(value: unknown): value is BonusState {
  return typeof value === "string" && (BONUS_STATES as readonly string[]).includes(value);
}

export type BonusPlan =
  | { ok: true; state: BonusState; note: string | null }
  | { ok: false; error: string };

/**
 * A bonus decision is a record, never a payment.
 *
 * The state is what the owner or a recruiter decided, and the note is the
 * sentence beside it. No amount is stored because this portal does not move
 * money: recording "PAID" here means somebody says it was paid, and the change
 * trail keeps who said so and when. Every transition is allowed, including a
 * correction, because a decision recorded wrongly is worse than one changed.
 */
export function planBonusDecision(input: {
  state: unknown;
  note?: unknown;
}): BonusPlan {
  if (!isBonusState(input.state)) {
    return { ok: false, error: "Choose a bonus state." };
  }
  const note = typeof input.note === "string" ? input.note.trim() : "";
  if (note.length > REFERRAL_BONUS_NOTE_MAX) {
    return {
      ok: false,
      error: `Keep the bonus note under ${REFERRAL_BONUS_NOTE_MAX} characters.`,
    };
  }
  return { ok: true, state: input.state, note: note || null };
}

/* -------------------------------------------------------------------------- */
/* Counting and ranking                                                        */
/* -------------------------------------------------------------------------- */

/** The two fields a count or a leaderboard needs from a referral row. */
export interface ReferralMeasure {
  stage: ApplicationStage | string | null;
  bonusState: BonusState;
}

export interface ReferralCounts {
  total: number;
  invited: number;
  applied: number;
  active: number;
  hired: number;
  closed: number;
  bonusPending: number;
  bonusPaid: number;
}

/**
 * Population counts: who sits where now, never how many moved.
 *
 * Every claim is in exactly one pipeline bucket, so `invited + active + hired +
 * closed` is the total. There is deliberately no conversion, rate or
 * denominator here — a referral board that says "3 of 10" invites a reader to
 * treat a denominator of people who have not applied yet as a failure.
 */
export function referralCounts(rows: readonly ReferralMeasure[]): ReferralCounts {
  const counts: ReferralCounts = {
    total: rows.length,
    invited: 0,
    applied: 0,
    active: 0,
    hired: 0,
    closed: 0,
    bonusPending: 0,
    bonusPaid: 0,
  };

  for (const row of rows) {
    if (!row.stage) counts.invited += 1;
    else counts.applied += 1;

    const progress = referralProgress(row.stage);
    if (progress.key === "hired") counts.hired += 1;
    else if (progress.key === "closed") counts.closed += 1;
    else if (progress.key !== "invited") counts.active += 1;

    if (row.bonusState === "PENDING") counts.bonusPending += 1;
    else if (row.bonusState === "PAID") counts.bonusPaid += 1;
  }

  return counts;
}

export interface LeaderboardEntry {
  profileId: string;
  name: string;
  total: number;
  hired: number;
  active: number;
  rank: number;
}

export interface LeaderboardReferral extends ReferralMeasure {
  profileId: string;
  name: string;
}

/**
 * The referrers, ordered by hires and then by the size of the book they brought.
 *
 * This is a ranking of populations, not a target: a person with no hires yet is
 * still on the board with their name and their number, and nobody is shown a
 * percentage. Ties fall to the name so the same data ranks the same way twice.
 */
export function referralLeaderboard(
  rows: readonly LeaderboardReferral[]
): LeaderboardEntry[] {
  const byPerson = new Map<string, LeaderboardEntry>();
  for (const row of rows) {
    const held = byPerson.get(row.profileId) ?? {
      profileId: row.profileId,
      name: row.name,
      total: 0,
      hired: 0,
      active: 0,
      rank: 0,
    };
    held.total += 1;
    const progress = referralProgress(row.stage);
    if (progress.key === "hired") held.hired += 1;
    else if (progress.key !== "invited" && progress.key !== "closed") held.active += 1;
    byPerson.set(row.profileId, held);
  }

  const ordered = [...byPerson.values()].sort(
    (left, right) =>
      right.hired - left.hired ||
      right.total - left.total ||
      left.name.localeCompare(right.name) ||
      left.profileId.localeCompare(right.profileId)
  );

  return ordered.map((entry, index) => ({ ...entry, rank: index + 1 }));
}

