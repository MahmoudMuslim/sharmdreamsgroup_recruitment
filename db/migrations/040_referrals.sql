-- ============================================================================
-- Who brought whom: the employee referral programme.
--
-- The portal already has a REFERRAL value in `application_source`, and nothing
-- writes it. An applicant could tick it themselves, which records a claim no member
-- of staff made, and no screen could answer the two questions a referral programme
-- exists to answer — which employee brought this person, and has anyone decided
-- what that is worth. This migration adds the table those answers live in.
--
-- Two doors put a row here, and they are the same claim:
--
--   * a durable per-person link, `/careers/<job>?ref=<code>`. The code is a column
--     on `user_profiles`, generated by the database, so a link keeps working when a
--     job is edited and a person cannot invent someone else's code by guessing a
--     name;
--   * a staff hand entry, for a candidate who applied another way or was referred
--     before the link existed. The claim is written with the referrer being the
--     signed-in staff member and the email being the whole key.
--
-- The claim is unique per (lower(email), job). That index, not the action, is what
-- makes first-claim-wins true when two recruiters submit at once: the second write
-- gets 23505 and the board names the existing claimant instead of showing two
-- people credited for one hire. Case is folded in the index because an address is
-- not case-sensitive and "Maya@Example.com" is the same person who applied as
-- "maya@example.com".
--
-- There is deliberately no stage column. A referral's progress IS the application's
-- stage, read when the board renders, so a stage move made anywhere in the portal
-- changes what the referral shows without a second writer having to remember to
-- copy it. A copied stage is a second truth that drifts the first day someone
-- moves an applicant through a path that does not know referrals exist.
--
-- `bonus_state` is a decision record, not a payment. No amount is stored because
-- this portal moves no money; PAID means a person said it was paid, and the change
-- trail keeps who said so and when. Every transition is allowed, including a
-- correction, because a decision recorded wrongly is worse than one changed.
--
-- `bonus_decided_by` and `bonus_decided_at` are written together by the action and
-- are nullable until the first decision. `bonus_note` is the sentence beside the
-- state, held to the 400-character bound the domain module also enforces.
--
-- Reads follow the four decisions the programme was approved on: every staff
-- member reads their own rows, a recruiter or the owner reads every row, and a
-- candidate reads none. `is_recruiter()` below is the wall behind the difference,
-- and it is a new helper rather than `is_staff()` because a hiring manager is staff
-- but must not see the whole company's referral book. Writes are split the same
-- way: a claim is inserted only by its own referrer, while reassigning a claim and
-- recording the bonus are a recruiter's two doors.
--
-- NOT APPLIED. This file is authored so the screen, the public door and the proof
-- can name it; running it is the owner's decision. `scripts/prove-referrals.mjs`
-- holds the refusal copy, so an unapplied file says "not stored yet" on screen
-- instead of reporting an empty board.
-- ============================================================================

alter table public.user_profiles
  add column if not exists referral_code text;

-- Five random bytes, hex, upper-case: ten characters that fit the domain module's
-- pattern and cannot be read back into a person's identity the way a name can.
alter table public.user_profiles
  alter column referral_code set default upper(encode(gen_random_bytes(5), 'hex'));

-- Existing rows get a code derived from their own id. `gen_random_bytes` would also
-- work, but a collision during a bulk backfill would abort the statement and leave
-- the migration half-applied; the id is already unique, so this backfill cannot
-- collide and the unique index below is a statement about the column, not a repair.
update public.user_profiles
   set referral_code = upper(substr(replace(id::text, '-', ''), 1, 10))
 where referral_code is null;

alter table public.user_profiles
  alter column referral_code set not null;

do $$ begin
  alter table public.user_profiles
    add constraint user_profiles_referral_code_check
    check (referral_code ~ '^[0-9A-F]{10}$');
exception when duplicate_object or duplicate_table or undefined_object then null; end $$;

create unique index if not exists user_profiles_referral_code_uniq
  on public.user_profiles (referral_code);

create table if not exists public.referrals (
  id uuid default gen_random_uuid(),
  tenant_id uuid,
  job_id uuid not null,
  application_id uuid,
  email text not null,
  full_name text,
  referrer_profile_id uuid not null,
  note text,
  bonus_state text default 'NONE'::text not null,
  bonus_note text,
  bonus_decided_by uuid,
  bonus_decided_at timestamp with time zone,
  created_at timestamp with time zone default now() not null,
  updated_at timestamp with time zone default now() not null,
  constraint referrals_pkey primary key (id),
  constraint referrals_bonus_state_check
    check (bonus_state in ('NONE', 'PENDING', 'PAID', 'DECLINED')),
  constraint referrals_email_check
    check (length(btrim(email)) > 3 and position('@' in email) > 1),
  constraint referrals_full_name_check
    check (full_name is null or length(btrim(full_name)) <= 160),
  constraint referrals_note_check
    check (note is null or length(note) <= 600),
  constraint referrals_bonus_note_check
    check (bonus_note is null or length(bonus_note) <= 400),
  constraint referrals_job_id_fkey
    foreign key (job_id) references job_openings (id) on delete cascade,
  constraint referrals_application_id_fkey
    foreign key (application_id) references applications (id) on delete set null,
  constraint referrals_referrer_profile_id_fkey
    foreign key (referrer_profile_id) references user_profiles (id) on delete cascade,
  constraint referrals_bonus_decided_by_fkey
    foreign key (bonus_decided_by) references user_profiles (id) on delete set null
);

comment on table public.referrals is
  'One staff member''s claim on one person for one role. The claim is unique per '
  '(lower(email), job); its progress is the linked application''s stage, read at '
  'display time and never copied here.';

comment on column public.referrals.email is
  'Folded by the unique index, not by the column: the address the claim was filed '
  'under, kept as typed after trimming so the board can print it back.';

comment on column public.referrals.application_id is
  'The application this claim resolved to, when the candidate applied. Null means '
  'the invitation has not been taken up yet, and is what the board renders as '
  '"Not applied yet" rather than as a stage.';

comment on column public.referrals.bonus_state is
  'NONE, PENDING, PAID or DECLINED — a decision recorded by a recruiter or the '
  'owner. Not a payment: this portal moves no money, and the trail keeps who said '
  'so and when.';

create unique index if not exists referrals_person_job_uniq
  on public.referrals (lower(email), job_id);

create unique index if not exists referrals_application_uniq
  on public.referrals (application_id)
  where application_id is not null;

create index if not exists referrals_referrer_idx
  on public.referrals (referrer_profile_id);
create index if not exists referrals_job_idx
  on public.referrals (job_id);
create index if not exists referrals_tenant_idx
  on public.referrals (tenant_id);

drop trigger if exists trg_referrals_updated on public.referrals;
CREATE TRIGGER trg_referrals_updated BEFORE UPDATE ON public.referrals FOR EACH ROW EXECUTE FUNCTION set_updated_at();

/*
 * A recruiter is the role that may read every claim and decide what the programme
 * pays. It is a function rather than an inline role test for the same reason
 * `is_staff()` is one: the policies that say "a recruiter reads every row" and "a
 * recruiter may reassign" should read as that sentence at the call site, and there
 * is one place to change if the role list ever does.
 */
create or replace function public.is_recruiter()
returns boolean
language sql stable security definer set search_path = public
as $$
  select exists (
    select 1 from user_profiles
    where auth_user_id = auth.uid()
      and role::text in ('SUPER_ADMIN', 'RECRUITER')
  );
$$;

alter table if exists public.referrals enable row level security;

/*
 * Own rows for everyone on staff; every row for a recruiter or the owner. The
 * hiring manager's narrower view is the point: the person who referred someone is
 * allowed to watch that referral, not to read the company's whole book.
 */
drop policy if exists "referrals_staff_read" on public.referrals;
create policy "referrals_staff_read" on public.referrals
  for SELECT
  to authenticated
  using (
    is_staff()
    and (is_recruiter() or referrer_profile_id = current_user_profile_id())
  );

/*
 * A claim is filed by the person it credits, never by a profile id in the browser.
 * The action binds the id from the session and this WITH CHECK is the copy that
 * holds for a request that arrives from somewhere else.
 */
drop policy if exists "referrals_own_add" on public.referrals;
create policy "referrals_own_add" on public.referrals
  for INSERT
  to authenticated
  with check (
    is_staff()
    and referrer_profile_id = current_user_profile_id()
  );

/*
 * Reassignment and the bonus decision are the recruiter's two doors. They share
 * one policy because both change the same row and both are refused to a hiring
 * manager by the same sentence; the action's role gates decide which columns each
 * door may touch.
 */
drop policy if exists "referrals_recruiter_change" on public.referrals;
create policy "referrals_recruiter_change" on public.referrals
  for UPDATE
  to authenticated
  using (is_recruiter())
  with check (
    is_recruiter()
    and referrer_profile_id is not null
  );

drop policy if exists "referrals_recruiter_remove" on public.referrals;
create policy "referrals_recruiter_remove" on public.referrals
  for DELETE
  to authenticated
  using (is_recruiter());

grant select, insert, update, delete on table public.referrals to authenticated;
grant select, insert, update, delete on table public.referrals to service_role;
revoke all on table public.referrals from anon;

grant execute on function public.is_recruiter() to anon;
grant execute on function public.is_recruiter() to authenticated;
grant execute on function public.is_recruiter() to service_role;

-- PostgREST caches its view of the schema, so a REST write to the new table is
-- refused as an unknown resource until the API reloads. Without this the board
-- would say "not stored yet" against a database that has the table.
notify pgrst, 'reload schema';

