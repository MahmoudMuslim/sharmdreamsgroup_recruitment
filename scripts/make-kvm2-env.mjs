// Build drop-in production env files for the KVM2 stack:
//   docker/.env.kvm2  -> copy to docker/.env   (compose/env-file, git-ignored)
//   .env.kvm2.local   -> copy to .env.local    (app env_file,   git-ignored)
//
// It reads the real third-party keys already present in the local `.env.local`
// (AI providers, WhatsApp outbound, SMTP) and mints FRESH production secrets
// (DB/PostgREST passwords, AUTH_JWT_SECRET, CRON_SECRET, staff fixture password).
// It prints only which keys were carried over and the output sizes — never a
// value — so this run adds no credential to any log.
//
// With both files in place a first `up` is the whole deploy: the db image applies
// db/schema.sql (46 tables, 99 policies, the 9-company reference set) and then
// db/initdb/04-seed-staff.sh creates the sign-ins, so no second command is
// needed to get a working stack. Verify with scripts/check-kvm2-env.mjs.
//
// Run from the repo root:   node scripts/make-kvm2-env.mjs
import fs from 'node:fs';
import crypto from 'node:crypto';

const root = process.cwd();
const srcPath = `${root}/.env.local`;

if (!fs.existsSync(srcPath)) {
  console.error('No .env.local found. Run this on the machine that holds the real keys.');
  process.exit(1);
}

const env = {};
for (const raw of fs.readFileSync(srcPath, 'utf8').split(/\r?\n/)) {
  const line = raw.trim();
  if (!line || line.startsWith('#')) continue;
  const eq = line.indexOf('=');
  if (eq === -1) continue;
  const key = line.slice(0, eq).trim();
  let val = line.slice(eq + 1).trim();
  if ((val.startsWith('"') && val.endsWith('"')) || (val.startsWith("'") && val.endsWith("'"))) {
    val = val.slice(1, -1);
  }
  env[key] = val;
}

const get = (k) => (env[k] && env[k].length > 0 ? env[k] : '');
const hex = (n) => crypto.randomBytes(n).toString('hex');

// Quote only when a value would otherwise break a dotenv/compose parser.
const fmt = (k, v) => (/[\s#]/.test(v) ? `${k}="${v.replace(/"/g, '\\"')}"` : `${k}=${v}`);

// Fresh production secrets (never reused from dev).
const secrets = {
  LOCAL_DB_PASSWORD: hex(16),
  LOCAL_PGRST_PASSWORD: hex(16),
  AUTH_JWT_SECRET: hex(32),
  LOCAL_STAFF_PASSWORD: hex(12),
  CRON_SECRET: hex(32),
};

// Reuse the existing encryption key so a restored pg_dump whose
// provider_credentials are already encrypted still decrypts. Fall back to a new
// one only if it is missing.
const settingsKey = get('SETTINGS_ENCRYPTION_KEY') || crypto.randomBytes(48).toString('base64url');

const composeLines = [
  '# KVM2 production — Compose env.  Copy: cp docker/.env.kvm2 docker/.env',
  '# Generated by scripts/make-kvm2-env.mjs. Git-ignored. Never commit.',
  '',
  '# --- Database ----------------------------------------------------------------',
  fmt('LOCAL_DB_PASSWORD', secrets.LOCAL_DB_PASSWORD),
  fmt('LOCAL_PGRST_PASSWORD', secrets.LOCAL_PGRST_PASSWORD),
  '',
  '# --- Session signing --------------------------------------------------------',
  fmt('AUTH_JWT_SECRET', secrets.AUTH_JWT_SECRET),
  'AUTH_TOKEN_ISSUER=sharm-dreams-prod',
  'AUTH_TOKEN_AUDIENCE=sdg_prod',
  '',
  '# --- Host ports (loopback only) ---------------------------------------------',
  'LOCAL_DB_PORT=54320',
  'LOCAL_GATEWAY_PORT=54321',
  '',
  '# --- First staff logins -----------------------------------------------------',
  '# db/initdb/04-seed-staff.sh creates these three on the first boot, from this',
  '# password. The owner address is the SUPER_ADMIN you sign in as — change it to',
  '# a mailbox you actually own; it is the login handle, nothing is emailed to it.',
  fmt('LOCAL_STAFF_PASSWORD', secrets.LOCAL_STAFF_PASSWORD),
  'STAFF_OWNER_EMAIL=admin@sharmdreamsgroup.cloud',
  'STAFF_OWNER_NAME=Group Owner',
  '',
  '# --- Cron -------------------------------------------------------------------',
  fmt('CRON_SECRET', secrets.CRON_SECRET),
  'WHATSAPP_EVERY=60',
  'GRADING_EVERY=300',
  'WHATSAPP_CRON_BATCH_SIZE=50',
  'GRADING_CRON_BATCH_SIZE=10',
  '',
  '# --- Front door / TLS -------------------------------------------------------',
  'NGINX_PORT=3000',
  'SDG_DOMAIN=sharmdreamsgroup.cloud',
  'ACME_EMAIL=admin@sharmdreamsgroup.cloud',
  'APP_URL_PUBLIC=https://sharmdreamsgroup.cloud',
  'COOKIE_SECURE=true',
  '',
  '# --- Stored bytes -----------------------------------------------------------',
  'UPLOADS_ROOT=/data/uploads',
  '',
];

const carried = ['OPENROUTER_API_KEY', 'GOOGLE_AI_STUDIO_API_KEY', 'OPENCODE_API_KEY',
  'QODER_API_KEY', 'CLOUDFLARE_AI_API_TOKEN', 'CLOUDFLARE_AI_ACCOUNT_ID',
  'NVIDIA_API_KEY', 'AI_GATEWAY_API_KEY', 'SMTP_HOST', 'SMTP_PORT', 'SMTP_USER',
  'SMTP_PASSWORD', 'EMAIL_FROM', 'WHATSAPP_TOKEN', 'WHATSAPP_PHONE_NUMBER_ID',
  'WHATSAPP_VERIFY_TOKEN'];

const appLines = [
  '# KVM2 production — app runtime env.  Copy: cp .env.kvm2.local .env.local',
  '# Generated by scripts/make-kvm2-env.mjs. Git-ignored. Never commit.',
  '',
  'APP_URL=https://sharmdreamsgroup.cloud',
  'NEXT_PUBLIC_APP_URL=https://sharmdreamsgroup.cloud',
  '',
  '# --- Credentials encryption -------------------------------------------------',
  fmt('SETTINGS_ENCRYPTION_KEY', settingsKey),
  '',
  '# --- Third-party keys (carried from the working .env.local) -----------------',
];

for (const k of carried) {
  const v = get(k);
  if (k === 'QODER_ACCESS_TOKEN') continue;
  if (v) appLines.push(fmt(k, v));
}
// The qoder worker reads a literal token; the file's "$QODER_API_KEY" never
// expanded, so pin it to the real key value.
if (get('QODER_API_KEY')) appLines.push(fmt('QODER_ACCESS_TOKEN', get('QODER_API_KEY')));

fs.writeFileSync(`${root}/docker/.env.kvm2`, composeLines.join('\n') + '\n');
fs.writeFileSync(`${root}/.env.kvm2.local`, appLines.join('\n') + '\n');

const present = carried.filter((k) => get(k));
console.log('wrote docker/.env.kvm2   (' + fs.statSync(`${root}/docker/.env.kvm2`).size + ' bytes)');
console.log('wrote .env.kvm2.local    (' + fs.statSync(`${root}/.env.kvm2.local`).size + ' bytes)');
console.log('third-party keys carried:', present.length + '/' + carried.length);
console.log('  ' + present.join(', '));
